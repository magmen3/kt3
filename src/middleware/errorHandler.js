// =====================================================================
// ФАЙЛ: src/middleware/errorHandler.js — ОБРАБОТЧИК ОШИБОК
// ---------------------------------------------------------------------
// Ловит все ошибки приложения и отвечает аккуратным JSON.
// 4 параметра (err, req, res, next) — по ним Express понимает, что это обработчик ошибок.
// Подключается в src/index.js последним.
//
// Как сюда попадают ошибки Prisma:
//   маршруты async, внутри await prisma.... Если Prisma выбрасывает ошибку,
//   Express 5 сам ловит её и передаёт сюда (в Express 4 нужен был бы try/catch).
//
// Коды ошибок Prisma (поле err.code):
//   P2002 — нарушение уникальности (такой email уже есть)
//   P2025 — запись не найдена (update/delete несуществующего id)
//   P2003 — нарушение внешнего ключа (удаляем пользователя, у которого есть посты)
// =====================================================================

function errorHandler(err, req, res, next) {
  // Клиент прислал сломанный JSON — такую ошибку выбрасывает express.json()
  if (err.type === 'entity.parse.failed') {
    return res.status(400).json({ error: 'Некорректный JSON в теле запроса' })
  }

  // Уникальность: 409 Conflict — «конфликт с существующими данными».
  // err.meta.target — список полей, например ['email']
  if (err.code === 'P2002') {
    const fields = err.meta && err.meta.target ? err.meta.target.join(', ') : 'поле'
    return res.status(409).json({ error: `Такое значение уже занято: ${fields}` })
  }

  // Запись не найдена — 404. Благодаря этому в PATCH и DELETE не нужно
  // отдельно искать запись: если её нет, Prisma сама выбросит P2025.
  if (err.code === 'P2025') {
    return res.status(404).json({ error: 'Запись не найдена' })
  }

  // Связь мешает удалить — 409. Пост ссылается на автора через authorId,
  // поэтому база не даёт удалить автора, пока у него есть посты.
  if (err.code === 'P2003') {
    return res.status(409).json({ error: 'Нельзя выполнить: запись связана с другими данными' })
  }

  // Все остальные ошибки
  const status = err.status || 500
  const message = status === 500 ? 'Внутренняя ошибка сервера' : err.message

  // Полную ошибку пишем в консоль сервера, клиенту — только общую фразу
  if (status === 500) {
    console.error(err)
  }

  res.status(status).json({ error: message })
}

module.exports = errorHandler
