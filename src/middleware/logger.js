// =====================================================================
// ФАЙЛ: src/middleware/logger.js — КАСТОМНЫЙ ЛОГГЕР
// ---------------------------------------------------------------------
// Для каждого запроса печатает в консоль строку вида:
//   GET /api/products?page=2 200 3ms
//   (метод, URL, статус ответа, время выполнения) — ровно как требует задание.
//
// Подключается в src/index.js САМЫМ ПЕРВЫМ: app.use(logger)
// Поэтому он видит вообще все запросы, даже те, что закончились ошибкой или 404.
//
// Что такое middleware:
//   Функция (req, res, next), через которую проходит запрос по пути к маршруту.
//   req  — входящий запрос (метод, адрес, тело...)
//   res  — объект ответа (через него отправляем ответ клиенту)
//   next — «передать запрос следующему middleware в цепочке»
// =====================================================================

function logger(req, res, next) {
  // Запоминаем время прихода запроса (в миллисекундах)
  const startTime = Date.now()

  // Статус ответа сейчас ещё неизвестен — маршрут ещё не отработал.
  // Поэтому подписываемся на событие 'finish' — оно сработает,
  // когда ответ будет полностью отправлен клиенту.
  res.on('finish', () => {
    const duration = Date.now() - startTime
    // req.originalUrl — полный адрес вместе с query, например /api/products?page=2
    console.log(`${req.method} ${req.originalUrl} ${res.statusCode} ${duration}ms`)
  })

  // Пропускаем запрос дальше. Без next() запрос «повиснет» и клиент не дождётся ответа.
  next()
}

module.exports = logger
